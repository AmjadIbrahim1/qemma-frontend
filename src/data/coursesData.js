// ==================== Helper Function ====================
export const getCourseById = (courseId) => {
  return coursesData.find(c => c.id === parseInt(courseId)) || null;
};

export const getCourseFullData = (courseId) => {
  const course = getCourseById(courseId);
  if (!course) return null;

  return {
    ...course,
    curriculum: getCurriculumData(courseId),
    assignments: getAssignmentsData(courseId),
    exams: getExamsData(courseId),
    liveSessions: getCourseLiveSessionsData(courseId),
    resources: getResourcesData(courseId),
    grades: getGradesData(courseId),
    attendance: getAttendanceData(courseId),
    discussions: getDiscussionsData(courseId),
  };
};